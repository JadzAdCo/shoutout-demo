const eol = src.includes("\r\n") ? "\r\n" : "\n";
if (src.includes(q(KEYS[0]) + ":")) throw new Error("review keys already present");

REPLACE_KEYS.forEach((key, k) => {
  const re = new RegExp(`^( *)${q(key).replace(/\./g, "\\.")}: .*?,?(\\r?\\n)`, "gm");
  let i = 0;
  src = src.replace(re, (match, indent, nl) => {
    const lang = CHROME_ORDER[i];
    i += 1;
    if (!lang) throw new Error(`${key}: more than ${CHROME_ORDER.length} hits`);
    return `${indent}${q(key)}: ${q(R[lang][k])},${nl}`;
  });
  if (i !== CHROME_ORDER.length) throw new Error(`${key}: ${i} hits`);
});

const anchor = /^( *)"floqai\.classicSearch": .*\r?\n/gm;
const hits = [...src.matchAll(anchor)];
if (hits.length !== CHROME_ORDER.length) throw new Error(`anchor hits ${hits.length}`);
let offset = 0;
hits.forEach((m, i) => {
  const lang = CHROME_ORDER[i];
  if (T[lang].length !== KEYS.length) throw new Error(`${lang} has ${T[lang].length} strings, expected ${KEYS.length}`);
  T[lang].forEach((value, k) => {
    const want = (T.en[k].match(/\{\w+\}/g) || []).sort().join();
    const got = (value.match(/\{\w+\}/g) || []).sort().join();
    if (want !== got) throw new Error(`${lang} ${KEYS[k]} placeholders ${got} != ${want}`);
  });
  const block = KEYS.map((key, k) => `${m[1]}${q(key)}: ${q(T[lang][k])},${eol}`).join("");
  const pos = m.index + m[0].length + offset;
  src = src.slice(0, pos) + block + src.slice(pos);
  offset += block.length;
});
