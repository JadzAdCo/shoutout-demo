function packFor(lang) {
  if (lang === "en") return {...EN};
  const localized = LOCALE[lang];
  if (!localized) throw new Error(`Missing locale block: ${lang}`);
  const keys = Object.keys(EN);
  const missing = keys.filter((k) => !Object.prototype.hasOwnProperty.call(localized, k));
  if (missing.length) throw new Error(`${lang} missing keys: ${JSON.stringify(missing)}`);
  return {...localized};
}

